const saved = (() => {
  try {
    return localStorage.getItem('nc.lang')
  } catch {
    return null
  }
})()

i18n.use(initReactI18next).init({
  resources: { en: { translation: en }, bg: { translation: bg } },
  lng: saved ?? (navigator.language.startsWith('bg') ? 'bg' : 'en'),
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
})

export function setLanguage(lng: 'en' | 'bg') {
  i18n.changeLanguage(lng)
  document.documentElement.lang = lng
  try {
    localStorage.setItem('nc.lang', lng)
  } catch {}
}

export default i18n
